export type MissionRuleStatus = 'implemented' | 'missing-source';

export type MissionScoringTiming = 'end-command-phase' | 'end-turn' | 'end-battle';

export type MissionScoringClauseKind =
  | 'fixed-if'
  | 'per-completed-action'
  | 'per-destroyed-enemy-unit'
  | 'per-operation-marker'
  | 'operation-marker-count-tier'
  | 'per-objective'
  | 'per-objective-if'
  | 'per-objective-with-bonus'
  | 'unsupported-event';

export type MissionObjectiveFilter = 'all' | 'non-home' | 'central';

export type MissionCondition =
  | 'controls-more-objectives-than-opponent'
  | 'controls-at-least-one-central-objective'
  | 'controls-at-least-one-non-home-objective'
  | 'controls-at-least-three-objectives'
  | 'controls-at-least-four-objectives'
  | 'controls-at-least-two-objectives'
  | 'controls-central-and-expansion-objectives'
  | 'controls-home-objective'
  | 'controls-opponent-home-objective'
  | 'controlled-objective-not-controlled-at-start-of-turn'
  | 'destroyed-enemy-near-objective'
  | 'destroyed-enemy-started-near-objective'
  | 'destroyed-enemy-in-terrain'
  | 'destroyed-enemy-started-near-central-objective'
  | 'destroyed-enemy-this-turn'
  | 'more-enemy-units-destroyed-than-friendly-previous-turn'
  | 'friendly-units-in-three-table-quarters'
  | 'friendly-units-in-four-table-quarters'
  | 'condemned-enemy-left-battlefield'
  | 'consecrated-objectives'
  | 'enemy-home-objective-consecrated'
  | 'extracted-intelligence'
  | 'three-operation-markers'
  | 'operation-marker-near-opponent-home-objective'
  | 'surveilled-enemy-units'
  | 'no-enemy-operation-markers'
  | 'triangulated-objectives'
  | 'no-enemy-units-wholly-within-territory'
  | 'sensor-sweep'
  | 'opponent-operation-marker-isolated'
  | 'committed-sabotage'
  | 'secured-asset'
  | 'vanguard-operation'
  | 'operation-markers-near-controlled-central-objectives'
  | 'booby-trapped-terrain'
  | 'destroyed-enemy-started-in-trapped-terrain'
  | 'only-one-operation-marker-isolated'
  | 'decoy-objectives'
  | 'four-decoy-objectives';

export interface MissionScoringClause {
  id: string;
  timing: MissionScoringTiming;
  rounds: 'any' | number[];
  kind: MissionScoringClauseKind;
  vp: number;
  condition?: MissionCondition;
  objectiveFilter?: MissionObjectiveFilter;
  bonusVp?: number;
  bonusCondition?: MissionCondition;
  minimumCount?: number;
  maximumCount?: number;
  sourceText: string;
  notes?: string;
}

export interface PrimaryMissionRuleSpec {
  name: string;
  edition: '11e';
  status: MissionRuleStatus;
  source: string;
  notes: string;
  scoring?: MissionScoringClause[];
}

export type SecondaryMissionMode = 'fixed' | 'tactical' | 'fixed-or-tactical';

export interface SecondaryMissionScoringClause {
  id: string;
  mode: SecondaryMissionMode;
  timing: string;
  vp: number;
  sourceText: string;
  notes?: string;
  maxVp?: number;
}

export interface SecondaryMissionRuleSpec {
  name: string;
  slug: string;
  deck: 'secondary';
  edition: '11e';
  status: MissionRuleStatus;
  mode: SecondaryMissionMode;
  source: string;
  notes: string;
  whenDrawn?: string;
  scoring: SecondaryMissionScoringClause[];
}

